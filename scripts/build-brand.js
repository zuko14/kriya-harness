import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

// Builds plugins/brand/client.js (the module DSH's Web UI loads) from
// plugins/brand/src/client.js by inlining the three Kriya fonts as
// @font-face rules: the UI runs offline on 127.0.0.1, so nothing is fetched.
// `--check` fails when the built file is stale (part of `npm run check`).

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..")
const require = createRequire(join(ROOT, "package.json"))
const SOURCE = join(ROOT, "plugins", "brand", "src", "client.js")
const OUT = join(ROOT, "plugins", "brand", "client.js")

// Variable fonts (OFL-1.1, notices in THIRD_PARTY_NOTICES.md), Latin subsets
export const FONTS = [
  { family: "KH Geist", file: "@fontsource-variable/geist/files/geist-latin-wght-normal.woff2", weight: "100 900" },
  { family: "KH Fraunces", file: "@fontsource-variable/fraunces/files/fraunces-latin-full-normal.woff2", weight: "100 900" },
  { family: "KH JetBrains Mono", file: "@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2", weight: "100 800" },
]

export function build() {
  const faces = FONTS.map(({ family, file, weight }) => {
    const data = readFileSync(require.resolve(file)).toString("base64")
    return `@font-face { font-family: "${family}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url(data:font/woff2;base64,${data}) format("woff2"); }`
  }).join("\n")
  const source = readFileSync(SOURCE, "utf8")
  if (!source.includes("__KRIYA_FONT_FACES__")) throw new Error("build-brand: placeholder missing in src/client.js")
  return (
    "// Generated by scripts/build-brand.js from src/client.js; do not edit.\n" +
    source.replace("__KRIYA_FONT_FACES__", () => faces)
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = build()
  if (process.argv.includes("--check")) {
    let current = ""
    try {
      current = readFileSync(OUT, "utf8")
    } catch {
      // Missing: stale
    }
    if (current !== built) {
      console.error("build-brand: plugins/brand/client.js is out of date; run npm run build:brand")
      process.exit(1)
    }
    console.log("build-brand: plugins/brand/client.js current")
  } else {
    writeFileSync(OUT, built)
    console.log(`build-brand: wrote plugins/brand/client.js (${Math.round(built.length / 1024)} KB)`)
  }
}
